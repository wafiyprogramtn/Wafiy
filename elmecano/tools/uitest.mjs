// UI test against the local server: story frames, courses, program modal, sign-up, admin.
import { createRequire } from 'module';
const { chromium } = createRequire(import.meta.url)(process.env.PW);
const [base, out, w, h] = process.argv.slice(2);
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: +w, height: +h } });
const errs = [];
p.on('pageerror', e => errs.push('pageerror: ' + e.message));
p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
await p.goto(base + '/?record');
await p.waitForFunction(() => window.__ready);
const shot = async (name, pv) => {
  await p.evaluate(pv => { document.documentElement.style.scrollBehavior = 'auto'; const s = document.getElementById('story'); scrollTo(0, s.offsetTop + (s.offsetHeight - innerHeight) * pv); }, pv);
  await p.evaluate(() => window.__renderAt(5000));
  await p.waitForTimeout(250);
  await p.evaluate(() => window.__renderAt(5000));
  await p.screenshot({ path: `${out}/${name}.jpg`, quality: 70 });
};
for (const v of [0, 0.25, 0.36, 0.55, 0.72, 0.95]) await shot('p' + v, v);
await p.goto(base + '/');
await p.waitForFunction(() => window.__ready);
await p.waitForTimeout(900);
await p.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; document.getElementById('formations').scrollIntoView(); });
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/courses.jpg`, quality: 70 });
await p.click('[data-program="ecu"]');
await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/program.jpg`, quality: 70 });
await p.click('.m-foot .js-signup');
await p.waitForTimeout(400);
await p.click('.f-submit');
await p.waitForTimeout(200);
await p.screenshot({ path: `${out}/form-errors.jpg`, quality: 70 });
await p.fill('#f-nom', 'Sami Trabelsi');
await p.fill('#f-tel', '+216 55 123 456');
await p.fill('#f-email', 'sami@example.tn');
await p.fill('#f-ville', 'Sousse');
await p.fill('#f-msg', 'Je suis disponible le samedi.');
await p.check('input[name=consent]');
await p.waitForTimeout(2600);
await p.screenshot({ path: `${out}/form-filled.jpg`, quality: 70 });
await p.click('.f-submit');
await p.waitForSelector('.f-done');
await p.screenshot({ path: `${out}/form-done.jpg`, quality: 70 });
// admin
const a = await b.newPage({ viewport: { width: +w, height: +h } });
a.on('pageerror', e => errs.push('admin pageerror: ' + e.message));
await a.goto(base + '/admin/');
await a.waitForSelector('#pw');
await a.fill('#pw', 'dev-password-123');
await a.click('#loginForm button');
await a.waitForSelector('.item');
await a.screenshot({ path: `${out}/admin.jpg`, quality: 70, fullPage: true });
console.log(errs.join('\n') || 'no errors');
await b.close();
